"""Build js/data.js from the TSV word lists.

Source: lesson vocabulary lists (词语表) of the New HSK Course 1-3 textbooks
(words, pinyin and lesson numbers). English glosses written for this project.
Run: python3 tools/build_data.py
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))

def rows(name):
    with open(os.path.join(HERE, name), encoding='utf8') as f:
        return [l.rstrip('\n').split('\t') for l in f if l.strip()]

levels, seen = [], set()
for lvl in (1, 2, 3):
    gloss = {}
    for hz, pos, en in rows(f'm{lvl}.tsv'):
        gloss[hz] = (pos, en)
    lessons = [{'n': int(n), 'zh': zh, 'en': en, 'grammar': g} for n, zh, en, g in rows(f'h{lvl}_lessons.tsv')]
    words = []
    for hz, py, n in rows(f'h{lvl}.tsv'):
        extra = hz.startswith('*')
        hz = hz.lstrip('*')
        if (hz, py) in seen:
            continue
        seen.add((hz, py))
        pos, en = gloss.get(f'{hz}|{py}') or gloss[hz]
        words.append({'id': f'{lvl}-{len(words)+1}', 'hz': hz, 'py': py, 'pos': pos, 'en': en,
                      'lv': lvl, 'ls': int(n), 'x': 1 if extra else 0})
    for L in lessons:
        L['words'] = [w['id'] for w in words if w['ls'] == L['n']]
    levels.append({'level': lvl, 'lessons': lessons, 'words': words})

out = os.path.join(HERE, '..', 'js', 'data.js')
with open(out, 'w', encoding='utf8') as f:
    f.write('// Generated by tools/build_data.py. Do not edit by hand.\n')
    f.write('window.HSK_DATA = ')
    json.dump(levels, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print('words per level:', [len(l['words']) for l in levels], 'lessons:', [len(l['lessons']) for l in levels])
